/* ===============================================================================
   MAIN APPLICATION CONTROLLER (app.js)
   =============================================================================== */

let rawDashboardData = null;
let currentCountry = 'ALL';
let currentTimeRange = 'ALL';
let currentMetric = 'cases';
let currentMapLayer = 'cases';

document.addEventListener('DOMContentLoaded', async () => {
  console.log("Initializing COVID-19 Analytics Web Dashboard...");
  
  // 1. Setup Tab Switching
  setupTabNavigation();

  // 2. Fetch JSON data produced by Python ETL pipeline
  await loadETLData();

  // 3. Populate Country Selector
  populateCountrySelector();

  // 4. Attach Event Listeners
  attachEventListeners();

  // 5. Initial Render
  updateDashboardView();
  
  // 6. Render DAX Explorer
  renderDAXLibrary('ALL');
});

// Setup Sidebar Tab Navigation
function setupTabNavigation() {
  const navItems = document.querySelectorAll('.nav-item');
  navItems.forEach(item => {
    item.addEventListener('click', () => {
      navItems.forEach(i => i.classList.remove('active'));
      document.querySelectorAll('.tab-pane').forEach(pane => pane.classList.remove('active'));

      item.classList.add('active');
      const targetTab = item.getAttribute('data-tab');
      const targetPane = document.getElementById(targetTab);
      if (targetPane) targetPane.classList.add('active');

      // Trigger Leaflet map resize if switching to map tab
      if (targetTab === 'tabMap') {
        setTimeout(() => {
          if (rawDashboardData) initLeafletMap(rawDashboardData.countries, currentMapLayer);
        }, 150);
      }
    });
  });
}

// Fetch JSON data generated by Python ETL
async function loadETLData() {
  try {
    const res = await fetch('data/covid_dashboard_data.json');
    if (!res.ok) throw new Error("Failed to load data JSON");
    rawDashboardData = await res.json();
    console.log("ETL Dataset loaded successfully:", rawDashboardData);
  } catch (err) {
    console.error("Error loading ETL dataset JSON:", err);
  }
}

// Populate Country Selector Dropdown
function populateCountrySelector() {
  const select = document.getElementById('countrySelect');
  if (!select || !rawDashboardData) return;

  rawDashboardData.countries.forEach(c => {
    const opt = document.createElement('option');
    opt.value = c.code;
    opt.textContent = `${c.name} (${c.code})`;
    select.appendChild(opt);
  });
}

// Attach Event Listeners to Slicers & Preset Buttons
function attachEventListeners() {
  // Country Dropdown
  const countrySelect = document.getElementById('countrySelect');
  countrySelect.addEventListener('change', (e) => {
    currentCountry = e.target.value;
    updateDashboardView();
  });

  // Time Range Presets
  document.querySelectorAll('[data-range]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      document.querySelectorAll('[data-range]').forEach(b => b.classList.remove('active'));
      e.target.classList.add('active');
      currentTimeRange = e.target.getAttribute('data-range');
      updateDashboardView();
    });
  });

  // Metric Presets
  document.querySelectorAll('[data-metric]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      document.querySelectorAll('[data-metric]').forEach(b => b.classList.remove('active'));
      e.target.classList.add('active');
      currentMetric = e.target.getAttribute('data-metric');
      updateDashboardView();
    });
  });

  // Map Layer Buttons
  document.querySelectorAll('[data-maplayer]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      document.querySelectorAll('[data-maplayer]').forEach(b => b.classList.remove('active'));
      e.target.classList.add('active');
      currentMapLayer = e.target.getAttribute('data-maplayer');
      if (rawDashboardData) initLeafletMap(rawDashboardData.countries, currentMapLayer);
    });
  });

  // DAX Category Dropdown
  const daxSelect = document.getElementById('daxCategorySelect');
  if (daxSelect) {
    daxSelect.addEventListener('change', (e) => {
      renderDAXLibrary(e.target.value);
    });
  }
}

// Update All Views
function updateDashboardView() {
  if (!rawDashboardData) return;

  // Filter time series data based on current selections
  let timeSeries = [...rawDashboardData.globalTimeSeries];
  if (currentTimeRange !== 'ALL') {
    timeSeries = timeSeries.filter(d => d.Date.startsWith(currentTimeRange));
  }

  // Update KPI Cards
  updateKPICards(rawDashboardData, currentCountry);

  // Render Charts
  renderMainTimeseries(timeSeries, currentMetric);
  renderCountryPie(rawDashboardData.countries);
  renderPositivityICU(timeSeries);
  renderMonthlyWaves(timeSeries);
  renderVaccineProgress(rawDashboardData.countries);
  renderVariantsChart();

  // Update Map if active
  initLeafletMap(rawDashboardData.countries, currentMapLayer);
}

// Update KPI Cards
function updateKPICards(data, countryCode) {
  let totalCases = 0;
  let totalDeaths = 0;
  let totalVax = 0;
  let cfr = 0;
  let surgeText = "Controlled";
  let surgeColor = "#00e676";

  if (countryCode === 'ALL') {
    totalCases = data.globalTotals.totalCases;
    totalDeaths = data.globalTotals.totalDeaths;
    totalVax = data.globalTotals.fullyVaccinated;
    cfr = data.globalTotals.globalFatalityRate;
    surgeText = "Moderate Surge";
    surgeColor = "#ffab00";
  } else {
    const c = data.countries.find(x => x.code === countryCode);
    if (c) {
      totalCases = c.totalCases;
      totalDeaths = c.totalDeaths;
      totalVax = c.fullyVaccinated;
      cfr = c.caseFatalityRate;
      
      if (cfr > 2.0 || c.movingAvgCases > 50000) {
        surgeText = "Critical Surge";
        surgeColor = "#ff5252";
      } else if (c.movingAvgCases > 15000) {
        surgeText = "Moderate Surge";
        surgeColor = "#ffab00";
      } else {
        surgeText = "Watch Status";
        surgeColor = "#ffd600";
      }
    }
  }

  // Animate values
  animateNumber('kpiTotalCases', totalCases);
  animateNumber('kpiTotalDeaths', totalDeaths);
  animateNumber('kpiTotalVax', totalVax);

  document.getElementById('kpiFatalityRateBadge').textContent = `${cfr}% CFR`;
  
  const vaxCoverage = ((totalVax / 7.8e9) * 100).toFixed(1);
  document.getElementById('kpiVaxCoverageBadge').textContent = `${vaxCoverage}% Coverage`;

  const surgeElem = document.getElementById('kpiSurgeIndex');
  if (surgeElem) {
    surgeElem.textContent = surgeText;
    surgeElem.style.color = surgeColor;
  }
}

// Helper to animate numbers
function animateNumber(elementId, targetVal) {
  const elem = document.getElementById(elementId);
  if (!elem) return;

  const current = parseInt(elem.textContent.replace(/,/g, '')) || 0;
  const diff = targetVal - current;
  const duration = 600;
  const steps = 20;
  const stepVal = diff / steps;
  let count = 0;

  const timer = setInterval(() => {
    count++;
    const nextVal = Math.round(current + stepVal * count);
    elem.textContent = nextVal.toLocaleString();
    if (count >= steps) {
      elem.textContent = targetVal.toLocaleString();
      clearInterval(timer);
    }
  }, duration / steps);
}
